import { chromium } from '@playwright/test'
const BASE='http://localhost:8088'
const b=await chromium.launch(); const c=await b.newContext(); const p=await c.newPage()
const errs=[]; const reqs=[]
p.on('pageerror',e=>errs.push('PE:'+String(e).slice(0,220)))
p.on('console',m=>{if(m.type()==='error')errs.push('C:'+m.text().slice(0,220))})
p.on('response',r=>{if(r.url().includes('/doriath/'))reqs.push(`${r.status()} ${r.request().method()} ${r.url().replace(BASE,'')}`)})
await p.goto(`${BASE}/index.php/login`,{waitUntil:'domcontentloaded'})
await p.locator('input[name="user"]').fill('admin'); await p.locator('input[name="password"]').fill('admin')
await p.locator('button[type="submit"]').first().click(); await p.waitForSelector('#header',{timeout:30000})
await p.goto(`${BASE}/index.php/apps/doriath/`,{waitUntil:'domcontentloaded'}); await p.waitForTimeout(2500)
await p.locator('.lock-screen input[type="password"]').first().fill('Oj',{force:true}); await p.waitForTimeout(400)
await p.evaluate(()=>{const bs=[...document.querySelectorAll('.lock-screen button')];const u=bs.find(b=>/Unlock/i.test(b.textContent||''));if(u)u.click()})
await p.waitForTimeout(3500)
await p.evaluate(()=>{const as=[...document.querySelectorAll('.app-navigation a')];const v=as.find(a=>/Vault/i.test(a.textContent||''));if(v)v.click()})
await p.waitForTimeout(2500)
await p.evaluate(()=>{const r=document.querySelector('.secret-list-item');if(r)r.click()})
await p.waitForTimeout(2500)
await p.evaluate(()=>{const bs=[...document.querySelectorAll('.secret-detail__actions button')];const s=bs.find(b=>/Share/i.test(b.textContent||''));if(s)s.click()})
await p.waitForTimeout(2000)
console.log('share-dialog present:', await p.locator('.share-dialog').count())
const btns = await p.evaluate(()=>[...document.querySelectorAll('body button')].map(b=>(b.textContent||'').trim()).filter(Boolean).slice(0,25))
console.log('buttons:', JSON.stringify(btns))
errs.length=0; reqs.length=0
await p.evaluate(()=>{const bs=[...document.querySelectorAll('body button')];const s=bs.find(b=>/Create link/i.test(b.textContent||''));if(s)s.click(); else console.error('NO CREATE LINK BUTTON')})
await p.waitForTimeout(5000)
console.log('reveal present:', await p.locator('.share-dialog__reveal').count())
console.log('requests:', reqs)
console.log('errors:', errs.slice(0,6))
await b.close()
