#!/usr/bin/env bash
# Prints phpseclib-chain.json: a partner chain minted the way Keepiq mints it, the CAs through openssl with lib/Service/certificate-extensions.cnf and the leaves through lib/Service/X509CertificateAssembler.php (phpseclib),
# as a leaf for a public key alone (issueForPublicKey) and re-signs of it and of an openssl-issued leaf (resignPreservingSubject). The leaves are valid for a year, so the tests verify them at their minting time.
# Needs PHP with ext-openssl and Keepiq's composer dependencies (composer install in the app root).
# Usage: bash src/testing/generate-phpseclib-chain.sh > src/testing/phpseclib-chain.json
set -euo pipefail
APP=$(cd "$(dirname "$0")/../../.." && pwd)
php -- "$APP" <<'PHP'
<?php
$app = $argv[1];
require "$app/vendor/autoload.php";
require_once "$app/lib/Support/PublicKeyLoaderAdapter.php";
require_once "$app/lib/Service/X509CertificateAssembler.php";

use OCA\Keepiq\Service\X509CertificateAssembler;

// CertificateIssuanceService::DEFAULT_DN; the CAs get 2048-bit keys and their own lifetimes, not CertificateAuthorityService's 4096 bits and days.
$dn = ['countryName' => 'NL', 'stateOrProvinceName' => 'Noord-Holland', 'localityName' => 'Amsterdam', 'organizationName' => 'Conduction', 'organizationalUnitName' => 'Keepiq'];
$cnf = "$app/lib/Service/certificate-extensions.cnf";
$sign = fn (string $section) => ['digest_alg' => 'sha256', 'config' => $cnf, 'x509_extensions' => $section];
$key = fn (int $bits) => openssl_pkey_new(['private_key_bits' => $bits, 'private_key_type' => OPENSSL_KEYTYPE_RSA]);
$csr = fn (string $cn, $privateKey) => openssl_csr_new(array_merge($dn, ['commonName' => $cn]), $privateKey, ['digest_alg' => 'sha256']);
$pem = function ($certificate): string {
	openssl_x509_export($certificate, $out);
	return $out;
};

$rootKey = $key(2048);
$root = $pem(openssl_csr_sign($csr('Keepiq Root CA', $rootKey), null, $rootKey, 3650, $sign('keepiq_root'), random_int(1, PHP_INT_MAX)));
$intermediateKey = $key(2048);
$intermediate = $pem(openssl_csr_sign($csr('Keepiq Intermediate CA', $intermediateKey), $root, $rootKey, 1825, $sign('keepiq_intermediate'), random_int(1, PHP_INT_MAX)));
openssl_pkey_export($intermediateKey, $intermediatePrivate);

// 4096 bits, as Keepiq user keys are.
$cn = 'bob@cloud.partner.example';
$bobKey = $key(4096);
$assembler = new X509CertificateAssembler(new \Psr\Log\NullLogger());
$leaf = $assembler->issueForPublicKey(openssl_pkey_get_details($bobKey)['key'], ['id-at-countryName' => 'NL', 'id-at-organizationName' => 'Conduction', 'id-at-commonName' => $cn], $intermediate, $intermediatePrivate);
$opensslLeaf = $pem(openssl_csr_sign($csr($cn, $bobKey), $intermediate, $intermediateKey, 365, $sign('keepiq_leaf'), random_int(1, PHP_INT_MAX)));
$leafResigned = $assembler->resignPreservingSubject($leaf, $intermediate, $intermediatePrivate);
$opensslLeafResigned = $assembler->resignPreservingSubject($opensslLeaf, $intermediate, $intermediatePrivate);
if ($leafResigned === null || $opensslLeafResigned === null) {
	fwrite(STDERR, "a re-sign failed\n");
	exit(1);
}

$der = fn (string $certificate) => base64_decode(preg_replace('/-----[A-Z ]+-----|\s/', '', $certificate));
echo json_encode([
	'_note' => 'TEST ONLY: throwaway keys and certificates generated by generate-phpseclib-chain.sh; they protect nothing.',
	'root' => $root,
	'rootFingerprint' => hash('sha256', $der($root)),
	'intermediate' => $intermediate,
	'leaf' => $leaf,
	'leafResigned' => $leafResigned,
	'opensslLeafResigned' => $opensslLeafResigned,
], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES), "\n";
PHP
