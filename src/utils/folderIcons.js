const FOLDER_ICON_MAP = Object.fromEntries(FOLDER_ICONS.map(e => [e.key, e.component]))

/**
 * Resolve an icon key to its component, or null when the key is unknown.
 *
 * @param {string|null|undefined} key Stored icon key
 * @return {object|null} Imported MDI component or null
 */
export function resolveFolderIcon(key) {
	if (!key) return null
	return FOLDER_ICON_MAP[key] ?? null
}

/**
 * Case-insensitive substring search over icon key + label.
 *
 * @param {string} query Search query
 * @return {Array<{key: string, label: string, component: object}>} Filtered icons
 */
export function searchFolderIcons(query) {
	const q = query.toLowerCase()
	return FOLDER_ICONS.filter(e =>
		e.key.toLowerCase().includes(q) || e.label.toLowerCase().includes(q),
	)
}
