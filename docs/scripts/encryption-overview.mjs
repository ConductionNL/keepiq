/* eslint-disable no-console -- a CLI script reports to the terminal */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { CRYPTO_PARAMETERS, technicalNames } from '../../src/crypto/parameters.js'

const HERE = dirname(fileURLToPath(import.meta.url))
export const PAGE_PATH = resolve(HERE, '../encryption-overview.md')

/**
 * Format a number with thousands separators, locale-independent.
 *
 * @param {number} value The number.
 * @return {string}
 */
function grouped(value) {
	return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, ',')
}

/**
 * The page's markdown for a set of crypto parameters.
 *
 * @param {object} [parameters] The parameters (defaults to the code's).
 * @return {string}
 */
export function renderOverview(parameters = CRYPTO_PARAMETERS) {
	const { secretValues, privateKey, attachments, passwordProtected } = parameters
	const names = technicalNames(parameters)
	return `<!--
  SPDX-FileCopyrightText: 2026 Conduction B.V. <info@conduction.nl>
  SPDX-License-Identifier: EUPL-1.2

  GENERATED by docs/scripts/encryption-overview.mjs from src/crypto/parameters.js.
  Do not edit by hand: change the crypto code and regenerate.
-->

# Encryption overview

Everything below is encrypted in your browser before it reaches the server.
The server stores only ciphertext and never sees your master password. The
values on this page are generated from the same code the web app runs, and the
Encryption section of your user settings shows the same list.

| What | How it is protected | Technical names |
| --- | --- | --- |
| Passwords and other secret values | Encrypted with your own ${secretValues.keyBits}-bit key pair. | ${names.secretValues} |
| Your private key | Locked with a key made from your master password, stretched ${grouped(privateKey.iterations)} times so guessing it is slow. | ${names.privateKey} |
| Attachments | Each file gets its own ${attachments.keyBits}-bit key, locked with your key pair. | ${names.attachments} |
| Encrypted backups, link shares and password-protected sends | Protected by their own password, stretched with a method that needs ${passwordProtected.memoryKiB / 1024} MiB of memory per guess. | ${names.passwordProtected} |

## What the numbers protect

- **Key size (${secretValues.keyBits}-bit RSA).** Decides how hard it is to break
  the key pair directly. Your secrets are encrypted to the public half; only the
  private half, which never leaves your browser unencrypted, can read them.
- **Iterations (${grouped(privateKey.iterations)} for ${privateKey.kdf}).** Every
  guess at your master password has to repeat the derivation this many times.
  The count only slows guessing; a long, unique master password is what keeps
  your private key safe.
- **Memory (${passwordProtected.memoryKiB / 1024} MiB for ${passwordProtected.kdf}).**
  Backups and links leave the vault, so their passwords are stretched with a
  method that also needs memory per guess, which makes guessing on special
  hardware expensive.

Comparing these numbers between products only makes sense together with what
each number protects: an iteration count says nothing about a key size.

## Your vault certificate

Your key pair comes with a certificate issued by the built-in certificate
authority. Its key type, key size and signature algorithm are read from the
certificate itself and shown on the Certificates page and in the Encryption
section of your user settings, next to its fingerprint, issuer and validity.
No private key material is shown anywhere.
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const page = renderOverview()
	if (process.argv.includes('--check')) {
		const current = readFileSync(PAGE_PATH, 'utf8')
		if (current !== page) {
			console.error('docs/encryption-overview.md is stale: run node docs/scripts/encryption-overview.mjs')
			process.exit(1)
		}
		console.log('docs/encryption-overview.md is up to date')
	} else {
		writeFileSync(PAGE_PATH, page)
		console.log('wrote docs/encryption-overview.md')
	}
}
